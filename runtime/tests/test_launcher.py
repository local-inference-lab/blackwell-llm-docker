def test_glm_base_recipe_semantic_parity_for_model_arguments():
    """Compare actual Bash DRY_RUN output; do not start an engine or import torch."""
    script = ROOT.parent / "recipes/glm53/serve-glm53-flash-nvfp4-dflash2.sh"
    result = subprocess.run(
        ["bash", str(script)],
        env={
            "PATH": os.environ["PATH"],
            "DRY_RUN": "1",
            "NUM_SPECULATIVE_TOKENS": "3",
            "MAX_CUDAGRAPH_CAPTURE_SIZE": "256",
            "PREFILL_SCHEDULE_INTERVAL": "1",
        },
        text=True,
        capture_output=True,
        check=True,
    )
    legacy = shlex.split(result.stdout.split("launch:", 1)[1])
    plan = resolve("glm53-flash", env={"MTP_DEPTH": "3"})
    for name in (
        "model",
        "tensor-parallel-size",
        "decode-context-parallel-size",
        "max-num-batched-tokens",
        "block-size",
        "max-model-len",
        "moe-backend",
        "linear-backend",
        "additional-config",
        "compilation-config",
        "speculative-config",
        "default-chat-template-kwargs",
        "override-generation-config",
    ):
        if name == "model":
            assert legacy[2] == plan.values[name]
            continue
        value = legacy[legacy.index("--" + name) + 1]
        resolved = plan.values[name]
        assert (
            json.loads(value) == resolved
            if isinstance(resolved, dict)
            else value == str(resolved)
        )
