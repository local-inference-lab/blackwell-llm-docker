def test_image_metadata_cannot_disguise_inherited_model_defaults():
    metadata = {
        "Id": "sha256:" + "1" * 64,
        "Config": {"Env": ["PATH=/opt/venv/bin", "CUDA_HOME=/usr/local/cuda"]},
    }
    audit_image_metadata(metadata)
    contract = make_contract(metadata, "2" * 64)
    assert contract["files"] == payload_hashes()
    assert not contract["qualified_serving_receipts"]
    metadata["Config"]["Env"].append("OMP_NUM_THREADS=1")
    with pytest.raises(ConfigError, match="OMP_NUM_THREADS"):
        audit_image_metadata(metadata)
    assert "VLLM_GLM53_MTP_DRAFT_HEAD" in owned_environment()


