MODELS = ["glm53-flash", "ds4-flash", "ds4-vision", "ds41-flash", "qwen38-flash-next"]


def test_generated_files_match_the_profile_registry():
    for model in MODELS:
        expected = (
            "# Generated by python -m runtime.generate compose; requires a profile-enabled image.\n"
            + yaml.safe_dump(compose(model), sort_keys=False)
        )
        assert (ROOT / "generated" / f"{model}.compose.yaml").read_text() == expected
    expected = (
        "<!-- Generated by python -m runtime.generate table; configuration, not performance evidence. -->\n\n"
        + parameter_table()
    )
    assert (ROOT / "generated/parameters.md").read_text() == expected


def test_profile_payload_does_not_bundle_other_models_source_overlays():
    payload = payload_hashes()
    assert "lil-serve" in payload and "install.sh" in payload
    assert not any("kimi-k3" in name or "source-overlay" in name for name in payload)


